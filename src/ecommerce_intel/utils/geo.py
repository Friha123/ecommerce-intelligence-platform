STATE_TO_REGION = {s: r for r, states in REGIONS.items() for s in states}


def haversine_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """Distance orthodromique entre deux points (km)."""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi, dlmb = p2 - p1, math.radians(lng2 - lng1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * 6371.0088 * math.asin(math.sqrt(a))


def state_label(code: str) -> str:
    return f"{code} · {STATE_NAMES[code]}" if code in STATE_NAMES else str(code)
